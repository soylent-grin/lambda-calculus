from lc.registry import slide
from lc.theme import *
from lc.widgets import *


@slide
class S32_Family(Talk):
    part = "практика"
    title = "Родословная: от λ к вашему языку"

    def draw(self):
        events = [
            ("1958", "Lisp, Маккарти", GOLD),
            ("1966", "ISWIM, Ландин", SKY),
            ("1973", "ML, Милнер", MINT),
            ("1975", "Scheme", GOLD),
            ("1990", "Haskell", SKY),
            ("2007", "C# 3.0, LINQ", MINT),
            ("2014", "Java 8", CORAL),
            ("2015", "ES2015: стрелки", GOLD),
        ]
        line = timeline(events, width=12.4, size=19)
        self.stage(line, buff=0.7)
        pts = self.points(
            [
                "Маккарти взял для Lisp нотацию λ, но признавался: «остальную книгу Чёрча я не понял»",
                "Ландин перевёл Algol 60 в λ и сказал: язык = λ-ядро + синтаксический сахар",
                "За полвека лямбды из академических языков пришли во все мейнстримные: C++11, Python, Go, Kotlin, Rust",
            ],
            size=24,
            width=11.6,
        )
        self.beat("Линия времени — от академии к мейнстриму.", FadeIn(line[0]))
        self.beat(
            "Первые четыре — академическая линия. Каждая следующая точка ближе к вашей работе.",
            LaggedStart(*[FadeIn(e, shift=UP * 0.06) for e in line[1]], lag_ratio=0.15),
            run_time=1.6,
        )
        for row, n in zip(
            pts,
            [
                "В Lisp ещё была динамическая область видимости — та самая ловушка с захватом.",
                "«The Next 700 Programming Languages» — одна из самых влиятельных статей о дизайне языков.",
                "Java шла к лямбдам почти 20 лет. Теперь их нет разве что в C.",
            ],
        ):
            self.beat(n, FadeIn(row, shift=RIGHT * 0.08))


@slide
class S33_Keep(Talk):
    part = "итог"
    title = "Что унести с собой"

    def draw(self):
        lines = [
            "*Самоприменение* — от парадокса Рассела до проблемы остановки, Ω и Y — главная нить лекции",
            "*1936:* «алгоритм» получил строгое определение. λ и машина Тьюринга равносильны: «что» и «как»",
            "*Весь язык* — три формы и одна подстановка. Порядок шагов не меняет ответ",
            "*Данные — это поведение.* *Рекурсия — неподвижная точка:* fact = F(fact), и Y её находит",
            "*НЛИ vs ТЛИ:* типы запрещают x x — исчезают Ω и Y «из коробки», зато вычисление конечно",
            "*ФП* — λ как стиль: чистые функции, функции как значения, эффекты на краю",
        ]
        pts = self.points(lines, size=26, width=12.0, gap=0.3)
        notes = [
            "x ∉ x, paradox(paradox), Ω, Y — одна и та же петля.",
            "Тезис Чёрча–Тьюринга: все разумные модели равны по силе.",
            "β и Чёрч–Россер.",
            "Кодирование Чёрча; от cos x = x к Y через улучшатель F.",
            "НЛИ/ТЛИ, x x.",
            "Лямбды в вашем языке, React, Redux, async/await — прямые потомки ответа на вопрос Гильберта.",
        ]
        hint = note("Песочница: ./scripts/playground.sh — пошаговая β-редукция в браузере", 22)
        self.stage(VGroup(pts, hint).arrange(DOWN, buff=0.45), buff=0.4)
        for row, n in zip(pts, notes):
            self.beat(n, FadeIn(row, shift=RIGHT * 0.08))
        self.beat("Вопросы? Можно остаться поиграть с песочницей или пройти уроки по порядку.", FadeIn(hint))

