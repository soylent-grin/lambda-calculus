from lc.registry import slide
from lc.theme import *
from lc.widgets import *


@slide
class S27_Types(Talk):
    part = "типы"
    title = "НЛИ и ТЛИ: главное отличие"

    def draw(self):
        self.gist(
            "*НЛИ* (бестиповое, 1936) — что угодно к чему угодно, есть Ω и Y. "
            "*ТЛИ* (типизированное, 1940) — запрет *x x*, вычисление всегда кончается"
        )
        rows = [
            ["", "НЛИ", "ТЛИ"],
            ["применение", "любой терм к любому", "f : A→B применяют только к A"],
            ["x x, Ω, Y", "допустимы", "нет типа → выражения нет"],
            ["рекурсия", "Y, самоприменение", "отдельный fix / let rec в языках"],
            ["практика", "JS, Lisp (динамика)", "ML, Haskell, Rust (статика)"],
        ]
        grid = table(rows, [2.4, 4.6, 4.6], size=24)
        foot = note("ТЛИ — ответ Чёрча и Рассела: самоприменение, из-за которого был Ω, в типах не типируется", 20)
        self.stage(VGroup(grid, foot).arrange(DOWN, buff=0.35), buff=0.45)
        self.beat("Два λ-исчисления Чёрча. Мы всю лекцию строили в НЛИ — отсюда Y.", FadeIn(grid[0]))
        notes = [
            "НЛИ = неограниченное применение. Ошибки — в runtime, как в JS.",
            "Главная строка: x должен быть и аргументом, и функцией одновременно — противоречие. Поэтому в ТЛИ нет Y «из коробки».",
            "Сильная нормализация: любое вычисление в чистом ТЛИ конечно. Языки добавляют рекурсию явно.",
            "Не «лучше/хуже»: динамика ближе к НЛИ, статическая проверка — к ТЛИ.",
        ]
        for row, n in zip(grid[1:], notes):
            self.beat(n, FadeIn(row, shift=UP * 0.05))
        self.beat("Следующий блок — куда это попало в компиляторы и в ваш код.", FadeIn(foot))
