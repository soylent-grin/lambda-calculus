@slide
class S03_Russell(Talk):
    part = "история"
    title = "Предыстория: парадокс Рассела, 1902"

    def draw(self):
        self.gist("Наивная теория множеств: *любое* свойство задаёт множество. Рассел нашёл в этом противоречие")
        r = serif("R  =  { x  |  x ∉ x }", 46, INK)
        q = serif("R ∈ R ?", 40, GOLD)
        yes = Text("если да  →  то R ∉ R", font=SANS, font_size=28, color=CORAL)
        no = Text("если нет  →  то R ∈ R", font=SANS, font_size=28, color=CORAL)
        spin = Text("↻", font=SANS, font_size=44, color=CORAL)
        card = code_card("const R = x => !x(x)\nR(R)  // ?", "js", size=22)
        answers = VGroup(yes, no).arrange(DOWN, buff=0.14, aligned_edge=LEFT)
        loop = VGroup(answers, spin).arrange(RIGHT, buff=0.35)
        left = VGroup(r, q, loop, card).arrange(DOWN, buff=0.28)
        pts = bullets(
            [
                "Кантор и Фреге строят всю математику из множеств и логики — как программу из маленького ядра",
                "R — множество всех множеств, которые *не содержат* себя. Любой ответ на «R ∈ R?» ведёт к противоположному",
                "Корень беды — *самоприменение*. Оно вернётся в проблеме остановки, в Ω и в Y",
            ],
            size=25,
            width=6.4,
        )
        self.split(left, pts, ratio=0.44)
        self.beat(
            "Кантор (1874) — бесконечности разного размера, Фреге (1879, 1893) — формальная логика и арифметика из логики. Множество — «всё, что обладает свойством». Звучит безобидно.",
            FadeIn(pts[0]),
        )
        self.beat("Определение выглядит законным: свойство «не содержать себя» понятно.", FadeIn(r), FadeIn(q), FadeIn(pts[1]))
        self.beat("Да — значит нет, нет — значит да. Бытовая версия: брадобрей бреет всех, кто не бреет себя сам.", FadeIn(answers))
        self.next_slide(notes="Это не «трудный вопрос», а противоречие внутри самих правил. А противоречивая система доказывает что угодно.")
        self.play(FadeIn(spin), run_time=0.3)
        self.play(Rotate(spin, TAU), run_time=0.9)
        self.beat(
            "Для программистов: R(R) = !R(R) — бесконечная рекурсия. 16 июня 1902 года Рассел написал Фреге, второй том его «Основных законов» уже был в печати. Ответы: типы Рассела, аксиомы Цермело (1908) и формализм Гильберта.",
            FadeIn(card, shift=UP * 0.06),
            FadeIn(pts[2]),
        )


