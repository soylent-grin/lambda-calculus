def app(body, arg, size=52):
    parts = [("(", INK, "lp"), *body, (")", INK, "rp"), arg]
    return formula(parts, size=size)


def ident(size=48):
    return app(
        [("λ", GOLD, "lam"), ("x", GOLD, "p"), (".", INK, "d"), ("x", SKY, "hole")],
        ("y", CORAL, "arg"),
        size=size,
    )


